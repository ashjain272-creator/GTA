"""Walking-skeleton demonstration (spec 17.15 precursor; Appendix I step 9).

Generates the synthetic fixture, runs every implemented stage, measures WER
against the fixture's ground truth, and records the outputs under reports/demo/.
Its purpose is to expose integration problems, not to demonstrate quality.
"""
from __future__ import annotations

import datetime as _dt
import shutil
import subprocess
import sys
from pathlib import Path

from .config import data_path
from .ingest.rights import RightsRefused
from .orchestrator.pipeline import Pipeline
from .qa.wer import wer
from .runreport import RunReport, StageFailed
from .storage.artefacts import read_json, write_json


def run_demo(cfg: dict, out_dir: Path | None) -> int:
    repo = Path(cfg["_repo"])
    stamp = _dt.datetime.now(_dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out_dir = out_dir or repo / "reports" / "demo" / stamp
    out_dir.mkdir(parents=True, exist_ok=True)
    fixture_dir = data_path(cfg, "sources") / "synthetic"
    fixture = fixture_dir / "demo_skeleton.mp4"
    truth_path = fixture_dir / "demo_skeleton.truth.json"
    rep = RunReport(cfg, "demo run (walking skeleton)")
    status, code = "ok", 0
    summary: dict = {"fixture": str(fixture)}
    try:
        with rep.stage("fixture") as st:
            if not fixture.is_file() or not truth_path.is_file():
                p = subprocess.run([sys.executable, str(repo / "scripts" / "make_synthetic_fixture.py"),
                                    str(fixture), "--truth", str(truth_path)], capture_output=True, text=True)
                if p.returncode != 0:
                    raise StageFailed("fixture_failed", "config", p.stderr.strip()[-400:])
            else:
                st["status"] = "cached"
        truth = read_json(truth_path)
        pipe = Pipeline(cfg, rep)
        sid = pipe.add_source(fixture, "A", game=None, grant=None, synthetic=True,
                              notes="synthetic fixture generated by scripts/make_synthetic_fixture.py")
        analysis = pipe.analyse(sid)
        with rep.stage("wer") as st:
            hyp = " ".join(s["text"] for s in analysis["transcript"]["segments"])
            ref = " ".join(line["text"] for line in truth["lines"])
            w = wer(ref, hyp)
            st.update(w)
            summary["wer"] = w | {"note": "synthetic TTS on clean bed; NOT representative of gaming audio"}
        cands = pipe.candidates(sid)
        plan = pipe.plan(sid)
        info, qa = pipe.render_and_qa(sid, plan)
        best = next(c for c in cands["candidates"] if c["candidate_id"] == plan["candidate_id"])
        exp_a, exp_b = truth["expected_best_moment_s"]
        b0, b1 = best["boundaries"]["start_us"] / 1e6, best["boundaries"]["end_us"] / 1e6
        covers = b0 <= exp_a + 0.5 and b1 >= exp_b - 1.0
        summary.update({
            "source_id": sid, "candidates": cands["counts"],
            "top_candidate": {"id": best["candidate_id"], "start_s": b0, "end_s": b1,
                              "viability": best["overall"]["viability"],
                              "covers_expected_moment": covers, "expected_s": [exp_a, exp_b]},
            "plan_id": plan["plan_id"], "short": info["path"], "qa_passed": qa["passed"],
            "qa_failed": qa["failed"], "qa_review_flags": qa["review_flags"],
        })
        if not covers:
            rep.warn("demo", "moment_missed", f"top candidate {b0:.1f}-{b1:.1f}s misses expected {exp_a}-{exp_b}s")
        if not qa["passed"]:
            status, code = "qa_failed", 1
        shutil.copy2(qa["contact_sheet"], out_dir / Path(qa["contact_sheet"]).name)
        write_json(out_dir / "qa.json", qa)
        write_json(out_dir / "candidates.json", cands)
        write_json(out_dir / "plan.json", plan)
    except (StageFailed, RightsRefused) as e:
        print(f"FAILED: {e}", file=sys.stderr)
        status, code = "failed", 2
    rep.data["demo_summary"] = summary
    path = rep.finish(out_dir, status)
    write_json(out_dir / "summary.json", summary | {"status": status, "run_report": path.name})
    print(f"demo {status}: {out_dir}")
    return code
