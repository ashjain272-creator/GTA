#!/usr/bin/env python3
"""Generate the project's own sound effects with FFmpeg synthesis.

Every effect is synthesised from oscillators and noise here, so the project
owns it outright: no third-party samples, no licence obligations. Output goes
to assets/sfx/ and is registered in config/assets.yaml (sha256 pinned).
Deterministic: noise sources are seeded.
"""
from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "assets" / "sfx"

# name: (lavfi source, filter chain, duration_s)
SFX = {
    "whoosh": ("anoisesrc=c=pink:a=0.6:seed=3:d=0.45:r=48000",
               "bandpass=f=1200:width_type=h:w=1600,afade=t=in:d=0.18,afade=t=out:st=0.2:d=0.25"),
    # thump: decaying 70 Hz sine plus a short mid-band noise transient; 4 ms attack, high-passed at 40 Hz
    # (an earlier pure sub-bass noise version overshot by up to +2.9 dB after AAC encoding)
    "impact": ("aevalsrc='0.8*sin(2*PI*70*t)*exp(-7*t)+0.35*(random(0)*2-1)*exp(-30*t)':s=48000:d=0.6",
               "highpass=f=40,lowpass=f=3000,afade=t=in:d=0.004,afade=t=out:st=0.4:d=0.2"),
    "pop": ("sine=f=880:d=0.09:r=48000",
            "afade=t=out:st=0.01:d=0.08,volume=0.6"),
    "riser": ("aevalsrc='0.35*sin(2*PI*(200+900*t*t)*t)':s=48000:d=1.2",
              "afade=t=in:d=0.9,afade=t=out:st=1.1:d=0.1"),
    "record_scratch": ("aevalsrc='0.4*sin(2*PI*(600-500*t)*t)*sin(2*PI*30*t)':s=48000:d=0.35",
                       "afade=t=out:st=0.25:d=0.1"),
}


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["# Asset registry (spec 4.8, A.3). Every asset used in an edit must be listed here.",
             "# Generated by scripts/make_sfx_assets.py; do not edit hashes by hand.", "sfx:"]
    for name, (src, chain, ) in ((k, v[:2]) for k, v in SFX.items()):
        out = OUT / f"{name}.wav"
        tmp = OUT / f".{name}.raw.wav"
        for args, dest in (([], tmp), (None, out)):
            if args is None:   # second pass: peak-normalise to -3 dBFS
                det = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(tmp), "-af", "volumedetect", "-f", "null", "-"],
                                     capture_output=True, text=True).stderr
                peak = float(det.split("max_volume:")[1].split("dB")[0])
                cmd = ["ffmpeg", "-v", "error", "-y", "-i", str(tmp), "-af", f"volume={-3.0 - peak:.2f}dB",
                       "-c:a", "pcm_s16le", str(dest)]
            else:
                cmd = ["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", src, "-af", chain,
                       "-ac", "2", "-c:a", "pcm_s16le", str(dest)]
            p = subprocess.run(cmd, capture_output=True, text=True)
            if p.returncode != 0:
                sys.exit(p.stderr)
        tmp.unlink()
        digest = hashlib.sha256(out.read_bytes()).hexdigest()
        lines += [f"  {name}:", f"    path: assets/sfx/{name}.wav", f"    sha256: {digest}",
                  "    licence: original work synthesised by this project (owned); no attribution required",
                  "    allowed: {commercial: true, derivatives: true}"]
    fonts = {"DejaVu Sans": "assets/fonts/DejaVuSans.ttf", "DejaVu Sans Bold": "assets/fonts/DejaVuSans-Bold.ttf",
             "Liberation Sans": "assets/fonts/LiberationSans-Regular.ttf",
             "Liberation Sans Bold": "assets/fonts/LiberationSans-Bold.ttf"}
    lines.append("fonts:")
    for fam, path in fonts.items():
        digest = hashlib.sha256((REPO / path).read_bytes()).hexdigest()
        lic = "Bitstream Vera licence (redistribution and embedding permitted), assets/fonts/DejaVu-LICENSE.txt" \
            if "DejaVu" in fam else "SIL Open Font License 1.1, assets/fonts/Liberation-LICENSE.txt"
        lines += [f"  {fam}:", f"    path: {path}", f"    sha256: {digest}", f"    licence: {lic}"]
    (REPO / "config" / "assets.yaml").write_text("\n".join(lines) + "\n")
    print("wrote", OUT, "and config/assets.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
